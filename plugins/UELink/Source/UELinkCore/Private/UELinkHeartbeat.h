#pragma once

#include "CoreMinimal.h"

/**
 * 心跳（2.25.0）：HTTP /rpc 和推送通道都由游戏线程驱动，游戏线程卡住（死循环、长加载、模态框）时面板只看到超时，
 * 分不清「游戏线程卡住」「整个进程停住（断点）」「已经退出」。这里在监听线程上单独应答一个端口（名片 alivePort）：
 * 连上就回一行 JSON（进程号、帧号、游戏线程上次走一帧是多久以前）然后断开，不经过游戏线程。
 * 进程被调试器停住时监听线程也停，连上了没人回，面板据此判断「整个进程停住」。
 */
namespace UELinkHeartbeat
{
	/** 起监听和游戏线程上的计帧，返回端口（拿不到时返回 0，名片就不写 alivePort）。游戏线程调用 */
	int32 Start();

	/** 停监听。游戏线程调用，重复调没关系 */
	void Stop();
}
